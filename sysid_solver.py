def solve_backlash(csv_data):
    df = pd.read_csv(io.StringIO(csv_data))
    
    # Extract max and min encoder readings during the zero-gyro oscillation phase
    diff_l = df['l_angle_deg'].max() - df['l_angle_deg'].min()
    diff_r = df['r_angle_deg'].max() - df['r_angle_deg'].min()
    max_diff_deg = max(diff_l, diff_r)
    
    # Arc length formula: s = theta_rad * radius
    backlash_m = (max_diff_deg * jnp.pi / 180.0) * WHEEL_RADIUS
    
    return float(backlash_m)

def solve_friction_and_torque(csv_data):
    df = pd.read_csv(io.StringIO(csv_data))
    
    # Find absolute maximum torque exerted right before / during slip
    max_load_l_Nm = df['l_load_mNm'].abs().max() / 1000.0
    max_load_r_Nm = df['r_load_mNm'].abs().max() / 1000.0
    
    tau_max = max(max_load_l_Nm, max_load_r_Nm)
    
    # Calculate Total Tractive Force: F = (tau_l + tau_r) / r
    F_total = (max_load_l_Nm + max_load_r_Nm) / WHEEL_RADIUS
    
    # Coulomb Friction: F = mu * m * g
    mu = F_total / (ROBOT_MASS * GRAVITY)
    
    return float(tau_max), float(mu)

def solve_terminal_velocity(csv_data):
    df = pd.read_csv(io.StringIO(csv_data))
    
    # Use the 95th percentile to average out sensor noise at top speed
    max_speed_deg = df['l_speed_deg_s'].abs().quantile(0.95)
    v_max_rad_s = max_speed_deg * jnp.pi / 180.0
    
    return float(v_max_rad_s)

@jax.jit
def fit_inertia_jax(alpha_arr, tau_net_arr):
    """
    JAX Accelerated Least Squares Fit
    Solves for I in the dynamic equation: I * alpha = tau_net
    Formula: I = sum(alpha * tau_net) / sum(alpha^2)
    """
    return jnp.sum(alpha_arr * tau_net_arr) / jnp.sum(alpha_arr * alpha_arr)

def solve_inertia(csv_data):
    df = pd.read_csv(io.StringIO(csv_data))
    
    time_s = df['time_ms'].values / 1000.0
    gyro_rad_s = df['gyro_z_rad_s'].values
    
    # Convert loads to standard Nm
    tau_l = df['l_load_mNm'].abs().values / 1000.0
    tau_r = df['r_load_mNm'].abs().values / 1000.0
    
    # Compute Angular Acceleration (alpha) using central differences
    # FIX: Pass time_s directly as the coordinate array!
    alpha = jnp.gradient(jnp.abs(gyro_rad_s), time_s)
    
    # Compute Net Torque applied to the robot frame
    # T_net = (F_r + F_l) * (Track Width / 2)
    F_l = tau_l / WHEEL_RADIUS
    F_r = tau_r / WHEEL_RADIUS
    tau_net = (F_l + F_r) * (TRACK_WIDTH / 2.0)
    
    # Filter arrays: We only want to fit data where the robot is actively accelerating
    mask = alpha > 5.0 
    alpha_active = jnp.array(alpha[mask])
    tau_net_active = jnp.array(tau_net[mask])
    
    # FIX: Safety check to prevent NaN if the mask is empty
    if len(alpha_active) == 0:
        print("WARNING: No active acceleration found in Test C. Using fallback inertia.")
        return 0.0025
    
    # Run JAX Least Squares fit
    I = fit_inertia_jax(alpha_active, tau_net_active)
    
    return float(I)

