"""KI-015: the random mission suite generator must produce a usable suite.

The generator had three separate defects. The first two - a config file that
does not exist in the repository, and treating ``solve()``'s
``(samples, stats)`` tuple as the samples - are fixed. The third was a
shadowed parameter: the solve result was called ``samples``, the same name
as the samples-per-segment count, so the *second* mission solved with the
first mission's sample **list** as the sample count and died inside the
optimizer with "can only concatenate list (not int) to list". Only the
second mission failed, so a one-mission run never showed it.

The mission suite itself is generated by ``research/suite.py`` and measured
by ``research/harness.py``; this script only solves the missions and writes
them out for a human to look at.
"""

import json
import os
import sys
import tempfile
import unittest

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXAMPLES = os.path.join(REPO_ROOT, "examples")
if REPO_ROOT not in sys.path:
    sys.path.insert(0, REPO_ROOT)
if EXAMPLES not in sys.path:
    sys.path.insert(0, EXAMPLES)

import generate_random_suite  # noqa: E402  (a script, not a package)


def _read(path):
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)


class TestRandomSuiteGenerator(unittest.TestCase):
    """The generator writes a suite a human can review."""

    def test_no_mission_raises(self):
        """Two missions, because the second one is where it used to die."""
        with tempfile.TemporaryDirectory() as tmp:
            records = generate_random_suite.run_suite(
                num_runs=2, output_dir=tmp, seed=7, samples=2)
        self.assertEqual(len(records), 2)
        for record in records:
            self.assertNotIn(
                "error", record,
                f"{record['id']} raised: {record.get('error')}")
            self.assertIn("status", record)
            self.assertIn("profile", record)

    def test_each_mission_writes_its_waypoints_and_its_trajectory(self):
        with tempfile.TemporaryDirectory() as tmp:
            generate_random_suite.run_suite(
                num_runs=2, output_dir=tmp, seed=7, samples=2)
            for index in range(2):
                run_dir = os.path.join(tmp, "m{:03d}".format(index))
                waypoints = _read(os.path.join(run_dir, "waypoints.json"))
                trajectory = _read(os.path.join(run_dir, "trajectory.json"))
        self.assertTrue(waypoints, "the mission has no waypoints")
        self.assertTrue(trajectory["trajectory"]["samples"],
                        "the mission has no trajectory")

    def test_the_metadata_is_written_for_every_mission(self):
        with tempfile.TemporaryDirectory() as tmp:
            generate_random_suite.run_suite(
                num_runs=2, output_dir=tmp, seed=7, samples=2)
            metadata = _read(os.path.join(tmp, "suite_metadata.json"))
        self.assertEqual(len(metadata), 2)
        self.assertEqual([m["id"] for m in metadata], ["m000", "m001"])


if __name__ == "__main__":
    unittest.main()
